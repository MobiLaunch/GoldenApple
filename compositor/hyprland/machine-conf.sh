#!/bin/sh
# Write the part of the Hyprland config that depends on the machine:
# ~/.config/hypr/golden-gate/machine.lua, loaded near the end of hyprland.lua.
# gg-session runs this before every start of the desktop; scripts/install.sh runs
# it once. Run it again after moving an install to other hardware.
out="${1:-${XDG_CONFIG_HOME:-$HOME/.config}/hypr/golden-gate/machine.lua}"
mkdir -p "$(dirname "$out")"

virt=$(systemd-detect-virt --vm 2>/dev/null) || virt=none
software=no
if [ "${LIBGL_ALWAYS_SOFTWARE:-0}" = 1 ] || ! ls /dev/dri/renderD* >/dev/null 2>&1; then
  software=yes
fi

{
  echo "-- Generated by machine-conf.sh (virtual machine: $virt, software rendering: $software)."
  echo "-- It is rewritten at every session start; put your own settings in hyprland.lua."

  if [ "$virt" != none ]; then
    cat <<'EOF'

-- Virtual screens report no physical size, which Hyprland's automatic scale reads
-- as an extremely dense display, so it doubles everything. Use 1×.
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = 1 })
EOF
  fi

  if [ "$software" = yes ]; then
    cat <<'EOF'

-- No GPU: every frame is drawn by the CPU (Mesa llvmpipe). Keep the glass, drop
-- what costs the most: a lighter blur, no window shadows, shorter and smaller zooms.
hl.config({ decoration = { blur = { passes = 1, size = 8 }, shadow = { enabled = false } } })
hl.animation({ leaf = "windowsIn", enabled = true, speed = 2, bezier = "smooth", style = "popin 100%" })
hl.animation({ leaf = "windowsOut", enabled = true, speed = 1, bezier = "smooth", style = "popin 100%" })
hl.animation({ leaf = "layersIn", enabled = true, speed = 3, bezier = "smooth", style = "fade" })
hl.animation({ leaf = "workspaces", enabled = true, speed = 4, bezier = "smooth", style = "slide" })
EOF
  fi
} > "$out.tmp" && mv "$out.tmp" "$out"
